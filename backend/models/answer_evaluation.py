from typing import List, Optional
from pydantic import BaseModel, Field


class CriterionMark(BaseModel):
    criterion: str = Field(
        ...,
        description="Name of the assessment criterion (e.g. Conceptual Accuracy, Coverage of Important Points, Technical Terminology, Explanation Quality, Relevance to Question)",
    )
    score: float = Field(
        ...,
        ge=0.0,
        le=2.0,
        description="Score awarded for this criterion out of 2.0",
    )
    max_score: float = Field(
        2.0,
        description="Maximum achievable score for this criterion",
    )
    feedback: str = Field(
        ...,
        description="Specific examiner commentary explaining the marks awarded or deducted for this criterion",
    )


class AnswerEvaluationResponse(BaseModel):
    score: float = Field(
        ...,
        ge=0.0,
        le=10.0,
        description="Overall evaluation score out of 10.0",
    )
    percentage: float = Field(
        ...,
        ge=0.0,
        le=100.0,
        description="Calculated score percentage (0-100%)",
    )
    grade: str = Field(
        ...,
        description="Academic letter grade awarded (e.g. A+, A, B, C, D, F)",
    )
    criteria_marks: List[CriterionMark] = Field(
        ...,
        description="Detailed criteria-wise breakdown across all 5 evaluation dimensions",
    )
    correct_points: List[str] = Field(
        ...,
        description="Accurate concepts, correct explanations, and valid points identified in the student's answer",
    )
    missing_points: List[str] = Field(
        ...,
        description="Important points or concepts present in the reference answer that were omitted by the student",
    )
    incorrect_statements: List[str] = Field(
        ...,
        description="Factually incorrect, unsupported, or conceptually inaccurate statements found in the answer",
    )
    suggestions_for_improvement: List[str] = Field(
        ...,
        description="Constructive, actionable tips and advice to elevate the student's answer",
    )
    improved_model_answer: str = Field(
        ...,
        description="A comprehensive, perfectly structured reference answer showcasing full-marks execution",
    )
    overall_feedback: str = Field(
        ...,
        description="Holistic assessment rationale and constructive comments from the university examiner",
    )


class EvaluateAnswerRequest(BaseModel):
    question: str = Field(
        ...,
        min_length=3,
        description="The practice question being answered",
        examples=["Explain the role of ATP synthase in oxidative phosphorylation."],
    )
    reference_answer: str = Field(
        ...,
        min_length=3,
        description="The benchmark reference or model answer",
        examples=[
            "ATP synthase is a multi-subunit rotary molecular motor embedded in the inner mitochondrial membrane. It utilizes the proton-motive force generated by the electron transport chain to synthesize ATP from ADP and inorganic phosphate via chemiosmosis."
        ],
    )
    student_answer: str = Field(
        ...,
        min_length=1,
        description="The student's submitted answer text to evaluate",
        examples=[
            "ATP synthase uses the hydrogen gradient across the membrane to produce ATP by turning ADP into ATP."
        ],
    )
    rubric: Optional[str] = Field(
        (
            "Evaluate strictly against reference answer across: "
            "1. Conceptual accuracy (0-2 pts), "
            "2. Coverage of important points (0-2 pts), "
            "3. Technical terminology (0-2 pts), "
            "4. Explanation quality (0-2 pts), "
            "5. Relevance to the question (0-2 pts). Total: 10 pts."
        ),
        description="Assessment rubric guidelines and criteria weightings",
    )
